// Localization Store (English & Tamil)
const LANG_STORAGE_KEY = 'aura_botanica_lang_v1';

let currentLang = localStorage.getItem(LANG_STORAGE_KEY) || 'en';
const langListeners = new Set();

export function getLanguage() {
  return currentLang;
}

export function setLanguage(lang) {
  if (lang === 'en' || lang === 'ta') {
    currentLang = lang;
    try {
      localStorage.setItem(LANG_STORAGE_KEY, lang);
    } catch (e) {
      console.error(e);
    }
    langListeners.forEach(fn => fn(currentLang));
    window.dispatchEvent(new CustomEvent('language:changed', { detail: { lang: currentLang } }));
  }
}

export function subscribeLanguage(callback) {
  langListeners.add(callback);
  return () => langListeners.delete(callback);
}

